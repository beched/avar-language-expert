#!/usr/bin/env python3
"""Generate ../sw.js with a full precache manifest (shell + icons + every mp3).

The cache name embeds a hash of the precached files' contents, so any content
change automatically invalidates the old cache -- no manual version bumping.
Run after build.py:  python3 gen_sw.py
"""
import hashlib, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

SHELL = ["index.html", "manifest.json", "icon-192.png", "icon-512.png", "icon-180.png"]
AUDIO = sorted(f for f in os.listdir(os.path.join(ROOT, "audio")) if f.endswith(".mp3"))

FILES = SHELL + [f"audio/{a}" for a in AUDIO]
missing = [f for f in FILES if not os.path.exists(os.path.join(ROOT, f))]
if missing:
    raise SystemExit(f"missing precache files: {missing}")

h = hashlib.sha256()
for f in FILES:
    h.update(f.encode())
    with open(os.path.join(ROOT, f), "rb") as fh:
        h.update(hashlib.sha256(fh.read()).digest())
VERSION = h.hexdigest()[:12]

PRECACHE = ["./"] + [f"./{f}" for f in FILES]

TPL = """// GENERATED by build/gen_sw.py -- do not edit by hand.
// Precaches the whole app (shell + icons + every audio sample) so it works
// with no network at all, including airplane mode on a cold start.
const CACHE = 'avar-course-%(version)s';
const PRECACHE = %(precache)s;
const OFFLINE_URL = './index.html';

// Cache each entry on its own: one bad response must not abort the install and
// leave the user with nothing cached.
async function precache() {
  const c = await caches.open(CACHE);
  const bust = { cache: 'reload' };
  await Promise.all(PRECACHE.map(async url => {
    try {
      const res = await fetch(new Request(url, bust));
      if (res && (res.ok || res.type === 'opaque')) await c.put(url, res);
    } catch (e) { /* keep going; the fetch handler will fill it in later */ }
  }));
}

self.addEventListener('install', e => {
  e.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    const ks = await caches.keys();
    await Promise.all(ks.filter(k => k !== CACHE && k.startsWith('avar-course-'))
                        .map(k => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', e => {
  if (e.data === 'skipWaiting') self.skipWaiting();
});

async function cacheFirst(request, fallbackUrl) {
  const cached = await caches.match(request, { ignoreSearch: true, ignoreVary: true });
  if (cached) return cached;
  try {
    const res = await fetch(request);
    if (res && res.ok && new URL(request.url).origin === self.location.origin) {
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put(request, copy)).catch(() => {});
    }
    return res;
  } catch (e) {
    if (fallbackUrl) {
      const fb = await caches.match(fallbackUrl);
      if (fb) return fb;
    }
    return new Response('', { status: 504, statusText: 'Offline' });
  }
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  // Navigations always resolve to the cached app shell when the network is gone.
  if (req.mode === 'navigate') { e.respondWith(cacheFirst(req, OFFLINE_URL)); return; }
  if (new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(cacheFirst(req, null));
});
"""

out = TPL % {"version": VERSION, "precache": json.dumps(PRECACHE, indent=0).replace("\n", "")}
with open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8") as fh:
    fh.write(out)
print(f"wrote ../sw.js : cache avar-course-{VERSION}, {len(PRECACHE)} precached entries")
