def norm(s):  # to Ӏ U+04C0
    for v in "ӏІіIl|!":
        s = s.replace(v, "Ӏ")
    return s

out = []
for tid, title, emoji, words in THEMES:
    items = []
    for ru, av in words:
        items.append({"ru": ru, "av": norm(av)})
    out.append({"id": tid, "title": title, "emoji": emoji, "words": items})

if __name__ == "__main__":
    p = os.path.join(os.path.dirname(__file__), "data.lex.json")
    json.dump(out, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    n = sum(len(t["words"]) for t in out)
    print(f"wrote {p}: {len(out)} themes, {n} words")
