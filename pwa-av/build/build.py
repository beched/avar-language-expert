# distractors come from the same lesson's already-introduced words -> always correct.
def _short(av): return 1 <= len(av.split()) <= 2 and "…" not in av
def _cat(av):
    """rough part-of-speech bucket so distractors match the answer (harder, not obvious)."""
    a = av.strip().lower()
    if re.search(r"(изе|азе|езе|озе|узе|ине)$", a): return "vinf"      # infinitive
    if re.search(r"(ана|уна|ула|ила|ола|ели|ана|ла)$", a): return "vfin"  # finite verb
    if re.search(r"(аб|яб|ав|ай|об|еб)$", a): return "adj"            # adjective/participle
    if re.search(r"(го|да|хъ|кь|лъ|бе|де|са|ниб|нибе)$", a): return "adv"  # adverb/local case
    return "noun"
def fill_exercises(minn=6):
    for li, l in enumerate(LESSONS):
        ex = l.setdefault("ex", [])
        # candidate words: this lesson's, prefer short single words, skip dup meanings
        cand = [w for w in l.get("words", []) if _short(w["av"])]
        # distractor pool: short av forms from this + neighbouring lessons
        dpool = []
        for l2 in LESSONS:
            for w in l2.get("words", []):
                if _short(w["av"]):
                    dpool.append(w["av"])
        dpool = list(dict.fromkeys(dpool))  # unique, keep order
        ci = 0
        used_ru = set()
        while len(ex) < minn and cand:
            w = cand[ci % len(cand)]; ci += 1
            if w["ru"] in used_ru:
                if ci > 3 * len(cand): break
                continue
            used_ru.add(w["ru"])
            # distractors that LOOK like the answer (same POS bucket / ending / length) —
            # so a verb question doesn't get an obvious noun option.
            ans = w["av"]; acat = _cat(ans)
            def _sim(a):
                s = 0
                if _cat(a) == acat: s += 3
                if a[-2:] == ans[-2:]: s += 2
                if abs(len(a) - len(ans)) <= 2: s += 1
                return s
            ranked = sorted((a for a in dpool if a != ans), key=lambda a: (-_sim(a), a))
            plausible = [a for a in ranked if _sim(a) >= 3] or ranked  # same-category pool
            top = plausible[:max(5, len(plausible) // 2)]
            # rotate distractor pick per lesson+index for variety, deterministic
            k = (li * 7 + ci * 3)
            d1 = top[k % len(top)]
            d2 = top[(k * 2 + 3) % len(top)]
            if d2 == d1: d2 = top[(k * 2 + 4) % len(top)]
            if d2 == d1:  # last resort
                d2 = next((a for a in ranked if a != d1), d1)
            opts = [ans, d1, d2]
            # place correct at a rotating position
            pos = ci % 3
            opts[0], opts[pos] = opts[pos], opts[0]
            ex.append({"t": "mcq", "q": "Как сказать «%s»?" % w["ru"], "opts": opts, "a": pos})
fill_exercises(6)

