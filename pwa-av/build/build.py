"""
Assemble the Avar course PWA:
  index.template.html  +  DATA (this file + data.lex.json + audio_manifest.json)
  -> ../index.html  (single file, all data inlined, offline)

Pedagogy rule: every word used in a lesson's examples/drills is listed in that
lesson's `words` (introduced explicitly) or an earlier lesson. Palochka = Ӏ U+04C0.
"""
import json, os, re
from arabisms import ARAB

HERE = os.path.dirname(os.path.abspath(__file__))
def P(*a): return os.path.join(HERE, *a)

LEX   = json.load(open(P("data.lex.json"), encoding="utf-8"))
try:   ENRICH = json.load(open(P("data.enrich.json"), encoding="utf-8"))
except Exception: ENRICH = {}
def ekey(av):  # match freqdeck's kp(): lowercase + canonical palochka U+04C0
    return av.lower().replace("ӏ", "Ӏ")
def enrich(w):  # attach dictionary forms/example/synonyms to a {ru,av,...} word
    e = ENRICH.get(ekey(w["av"]))
    if not e: return w
    o = dict(w)
    for f in ("forms", "ex", "alts"):
        if e.get(f) and not o.get(f): o[f] = e[f]
    return o
try:   FREQ = json.load(open(P("data.freq.json"), encoding="utf-8"))
except Exception: FREQ = []
try:   AUDIO = json.load(open(P("audio_manifest.json"), encoding="utf-8"))
except Exception: AUDIO = {}

I = "Ӏ"  # canonical palochka
def n(s):
    for v in "ӏІіIl":
        s = s.replace(v, I)
    return s

def lx(theme):  # pull a theme's words as {ru,av} list
    for t in LEX:
        if t["id"] == theme: return t["words"]
    return []
def pick(theme, *rus):  # pick specific russians from a theme, keep order
    d = {w["ru"]: w for w in lx(theme)}
    return [d[r] for r in rus if r in d]

