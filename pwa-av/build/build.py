def with_audio(l, i, h, ea, er):
    return {"L": l, "ipa": i, "hint": h, "ex": (n(ea) if ea else None),
            "exru": er, "audio": AUD.get(nk(l))}

def pool_items(v):
    out = []
    for t in v:
        d = {"av": n(t[0]), "ru": t[1]}
        if len(t) > 2: d["p"] = t[2]
        out.append(d)
    return out

