# cls: 'I' male-person, 'II' female-person, 'III' thing/animal, 'PL' plural
def W(ru, av, cls=None):
    d = {"ru": ru, "av": n(av)}
    if cls: d["cls"] = cls
    return d

# convenience: attach class to a theme word
def Wc(theme, ru, cls):
    for w in lx(theme):
        if w["ru"] == ru: return W(ru, w["av"], cls)
    raise KeyError(ru)

