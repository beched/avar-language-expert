I = "Ӏ"  # canonical palochka
def n(s):
    for v in "ӏІіIl":
        s = s.replace(v, I)
    return s

def lx(theme):  # pull a theme's words as {ru,av} list
    for t in LEX:
        if t["id"] == theme: return t["words"]
    return []
def pick(theme, *rus):  # pick specific russians from a theme, keep order
    d = {w["ru"]: w for w in lx(theme)}
    return [d[r] for r in rus if r in d]

